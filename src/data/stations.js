export const searchStations = (query) => {
  if (!query || typeof query !== 'string') return stations.slice(0, 10);
  const q = query.trim().toLowerCase();
  if (q.length === 0) return stations.slice(0, 10);

  const matched = stations.filter(s => 
    s.name.toLowerCase().includes(q) || 
    s.code.toLowerCase().includes(q) ||
    s.city.toLowerCase().includes(q) ||
    s.state.toLowerCase().includes(q)
  );

  if (matched.length > 0) {
    return matched;
  }

  // If no match in dataset, create a dynamic station entry so any Indian city/district typed by user works seamlessly
  const capitalized = query.trim().charAt(0).toUpperCase() + query.trim().slice(1);
  const generatedCode = query.trim().replace(/[^a-zA-Z]/g, '').toUpperCase().slice(0, 4) || 'STN';
  return [
    {
      code: generatedCode,
      name: `${capitalized} Railway Station`,
      city: capitalized,
      state: 'India'
    }
  ];
};
